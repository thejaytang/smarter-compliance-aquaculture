def translate(sql, names):
    """Map declared SQLite object identifiers, leaving data literals untouched."""
    catalog = bool(re.search(r'\bsqlite_(?:master|schema)\b|\btable_info\s*\(', sql, re.I))
    def replace(m):
        t=m.group(0)
        if t.startswith("'"):
            key=t[1:-1].replace("''", "'")
            return "'"+names.get(key,key)+"'" if catalog else t
        if t.startswith(('/*','--')):return t
        if t.startswith(('"','[')):
            key=t[1:-1];return '"'+names.get(key,key)+'"'
        return names.get(t,t)
    return TOKEN.sub(replace,sql)


class Connection(sqlite3.Connection):
    names = None
    validator = None
    routed = False
    def execute(self, sql, parameters=(), /):
        if self.routed and re.search(r'PRAGMA\s+journal_mode\s*=\s*WAL',sql,re.I):
            sql='PRAGMA journal_mode=DELETE'
        if self.names:
            sql=translate(sql,self.names)
            if 'sqlite_master' in sql or 'sqlite_schema' in sql:
                parameters=tuple(self.names.get(v,v) if isinstance(v,str) else v for v in parameters)
        return super().execute(sql,parameters)
    def executemany(self, sql, parameters, /):
        return super().executemany(translate(sql,self.names) if self.names else sql,parameters)
    def executescript(self, script, /):
        # Unlike sqlite3.executescript, do not silently commit a caller's atomic
        # cross-database transaction before executing schema statements.
        pending=''
        for line in script.splitlines(keepends=True):
            for char in line:
                pending+=char
                if char==';' and sqlite3.complete_statement(pending):
                    self.execute(pending);pending=''
        if pending.strip():self.execute(pending)
        return self.cursor()
    def commit(self):
        if self.validator and self.in_transaction:self.validator(self)
        return super().commit()
    def __exit__(self, kind, value, trace):
        try:
            if kind is None:self.commit()
            else:self.rollback()
        except BaseException:
            self.rollback();raise
        finally:self.close()


def connect(database, *args, **kwargs):
    original=str(database)
    memory_uri=kwargs.get('uri') and original.startswith('file:') and (
        urlsplit(original).path==':memory:' or parse_qs(urlsplit(original).query).get('mode')==['memory'])
    if original in ('', ':memory:') or memory_uri:
        kwargs['factory']=Connection
        db=sqlite3.connect(database,*args,**kwargs)
        db.execute('PRAGMA foreign_keys=ON')
        return db
    if original.startswith('file:'):
        uri=urlsplit(original)
        authority='//'+uri.netloc if uri.netloc and uri.netloc!='localhost' else ''
        path=Path(logical_path(url2pathname(authority+uri.path)))
    else:path=Path(original)
    if original.startswith('file:') and kwargs.get('uri'):
        database=sqlite_uri(path)+('?' + uri.query if uri.query else '')
    elif not original.startswith('file:') and original not in ('', ':memory:'):
        database=path
    marker=path.parent/'.storage.json'
    names={};routed=False
    if marker.is_file():
        config=json.loads(marker.read_text(encoding='utf-8'))
        entry=config.get(path.name)
        if entry:
            routed=True
            target=(marker.parent/entry['database']).resolve()
            if kwargs.get('uri'):
                query=urlsplit(original).query
                database=sqlite_uri(target)+('?' + query if query else '')
            else:database=target
            prefix=entry.get('prefix','')
            if prefix:names={n:prefix+n for n in SYSTEM2_TABLES|SYSTEM2_INDEXES}
    kwargs['factory']=Connection
    db=sqlite3.connect(database,*args,**kwargs)
    db.names=names
    db.routed=routed
    db.execute('PRAGMA foreign_keys=ON')
    return db



def operational_root(folder):
    """Keep replaceable System2 markers outside source evidence after migration."""
    folder=Path(folder)
    marker=folder/'.storage.json'
    if not marker.is_file():return folder
    entry=json.loads(marker.read_text(encoding='utf-8')).get('workflow.sqlite')
    if not entry:return folder
    database=(folder/entry['database']).resolve()
    # Only explicit four-store redirects determine the workspace runtime.
    if database.name!='system2.sqlite' or database.parent.name!='databases' or database.parent.parent.name!='workspace':
        return folder
    branch=entry.get('prefix') or 'main'
    if not re.fullmatch(r'[A-Za-z0-9_]+',branch):raise ValueError('Invalid System2 branch identity.')
    return database.parent.parent.parent/'runtime/state/system2'/branch


def alias(folder, filename, database, prefix=''):
    """Write an idempotent relative-path redirect; never copy a live SQLite file."""
    import os
    folder=Path(folder);folder.mkdir(parents=True,exist_ok=True)
    path=folder/'.storage.json'
    value=json.loads(path.read_text()) if path.exists() else {}
    value[filename]={'database':os.path.relpath(str(database),str(folder)),'prefix':prefix}
    raw=json.dumps(value,indent=2)+'\n'
    if not path.exists() or path.read_text()!=raw:
        temporary=path.with_suffix('.tmp');temporary.write_text(raw);temporary.replace(path)


def table_names(db):
    return {r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}


def copy_tables(source, target, include=None, prefix='', drop_cross_fk=False):
    """Stopped/coordinated migration. Preserve every row, ID and JSON byte."""
    with closing(sqlite3.connect(source)) as src, closing(sqlite3.connect(target)) as dst:
        objects=list(src.execute("SELECT type,name,tbl_name,sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END"))
        selected={n for t,n,_,_ in objects if t=='table' and (include is None or include(n))}
        names={n:prefix+n for _,n,t,_ in objects if t in selected}
        dst.execute('BEGIN IMMEDIATE')
        try:
            for kind,name,table,sql in objects:
                if table not in selected:continue
                if drop_cross_fk:
                    sql=re.sub(r',\s*FOREIGN KEY\(session_id,session_revision\) REFERENCES requirement_steps\(session_id,revision\)','',sql)
                dst.execute(translate(sql,names))
                if kind=='table':
                    cols=[r[1] for r in src.execute('PRAGMA table_info("'+name+'")')]
                    columns=','.join('"'+c+'"' for c in cols)
                    rows=src.execute('SELECT '+columns+' FROM "'+name+'"').fetchall()
                    dst.executemany('INSERT INTO "'+names[name]+'" ('+columns+') VALUES('+','.join('?' for _ in cols)+')',rows)
                    got=dst.execute('SELECT '+columns+' FROM "'+names[name]+'"').fetchall()
                    if got!=rows:raise ValueError('Migration changed records: '+name)
            dst.commit()
        except BaseException:dst.rollback();raise
        return {n:src.execute('SELECT count(*) FROM "'+n+'"').fetchone()[0] for n in selected}
