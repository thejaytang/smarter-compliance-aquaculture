"""SQLite boundary shared by component interpreters (standard library only).

Aliases are generated by the explicit migration, never supplied by HTTP clients.
System2 retains its branch-specific tables in one owning file. SQL translation
touches identifiers only; source text and bound values are never rewritten.
"""
